# Fail if any assertion is false.
if echo "$RESULT" | grep -q ':false'; then
  echo "FAIL: one or more data-driven assertions were false (see above)"
  exit 1
fi
echo "PASS: all protection thresholds + tier-1 lists are data-driven from consolidated cloud-data"

# ═══════════════════════════════════════════════════════════════════════════
# PART 2 — runtime: drive crit → clear and prove the shed has an inverse.
# ═══════════════════════════════════════════════════════════════════════════
# The shed list path is a literal /run/load-shedder.shed-list inside the
# shedder, so this section needs a writable /run. It is gated rather than
# redirected because rewriting the script to test it would test a script that
# is not the one we ship.
echo
echo "== PART 2: un-shed path (stubbed docker, scripted PSI) =="

SHED_LIST=/run/load-shedder.shed-list
FIRED=/run/load-shedder.fired

# Never race a real shedder: it owns these files and this test truncates them.
if [ -e "$SHED_LIST" ] || systemctl is-active --quiet load-shedder.service 2>/dev/null; then
  echo "SKIP(runtime): a live load-shedder owns /run/load-shedder.* on this host"
  exit 0
fi
# The GHA runner is not root, so without sudo this gate used to SKIP and exit 0
# on the one host that runs the tester — every PART 2 scenario read as coverage
# while asserting nothing. Everything the shedder calls that matters is stubbed,
# so running it as root on a throwaway runner touches only /run/load-shedder.*.
RUN_AS=""
if ! ( : > "$SHED_LIST" ) 2>/dev/null; then
  if sudo -n true 2>/dev/null; then
    RUN_AS="sudo -n"
  elif [ -n "${GITHUB_ACTIONS:-}" ]; then
    echo "::error::PART 2 cannot write /run and has no sudo — the shedder scenarios would not run"
    exit 1
  else
    echo "SKIP(runtime): /run is not writable — re-run as root to exercise the un-shed loop"
    exit 0
  fi
fi
$RUN_AS rm -f "$SHED_LIST"

cat > "$RENDER_NIX" <<'EOF'
let lib = import <nixpkgs/lib>;
in (import ./protection/load-shedder.nix {
     config = {}; pkgs = {}; inherit lib; ramMB = 1024; vmName = "oci-apps";
   }).home.file.".local/share/system-protection/load-shedder.sh".text
EOF

SHEDDER="$WORK/load-shedder.sh"
# --json + jq, not --raw: nix-instantiate has no --raw (that is `nix eval`), so
# this line failed on the first CI run that ever reached it.
nix-instantiate --eval --strict --json "$RENDER_NIX" | jq -r . > "$SHEDDER"

# Tier-1 comes from the rendered script, not from a copy of the JSON in this
# test: duplicating the list here would make the test pass while the shipped
# script protects something else.
TIER1="$(sed -n 's/^TIER1_SERVICES="\([^"]*\)".*/\1/p' "$SHEDDER" | head -1)"
[ -n "$TIER1" ] || { echo "FAIL: no TIER1_SERVICES in rendered script"; exit 1; }
# Sheddable fixtures. ntfy-exporter shares a prefix with tier-1 "ntfy" on
# purpose: a prefix match instead of an equality match would wrongly protect it.
# umami/umami-db are the measured dependency pair (see COMPOSE_LABELS): "umami"
# sorts before "umami-db", so any un-shed that ignores depends_on starts the
# dependent first.
SHEDDABLE="my-ai-api agent-runner-1 ntfy-exporter agent-runner-2 umami umami-db"
# Compose labels as `docker inspect` reports them: name|project|service|depends_on.
COMPOSE_LABELS="umami|umami|umami|umami-db:service_healthy:false
umami-db|umami|umami-db|"
echo "   tier1 (from rendered script): $TIER1"
echo "   sheddable fixtures:           $SHEDDABLE"

AWK_REAL="$(command -v awk)"
FAILED=0

assert() { # $1 = description, $2... = predicate command
  local desc="$1"; shift
  if "$@"; then echo "  ok   $desc"; else echo "  FAIL $desc"; FAILED=$((FAILED + 1)); fi
}

# Scenario builder. $1 = name, $2 = newline PSI sequence, $3 = names whose
# `docker start` must fail. Leaves everything it recorded under $SCEN.
run_scenario() {
  SCEN="$WORK/$1"
  mkdir -p "$SCEN/bin"
  printf '%s\n' $2 > "$SCEN/psi-seq"
  printf '%s\n' ${3:-} | grep -v '^$' > "$SCEN/start-fails" || true
  echo 1 > "$SCEN/psi-cursor"
  : > "$SCEN/log"; : > "$SCEN/docker-calls"; : > "$SCEN/starts"
  : > "$SCEN/timeline"; : > "$SCEN/ntfy"; : > "$SCEN/systemctl-calls"
  printf '%s\n' $TIER1 $SHEDDABLE | sort > "$SCEN/running"
  cp "$SCEN/running" "$SCEN/exists"
  printf '%s\n' "$COMPOSE_LABELS" > "$SCEN/labels"
  #   SLOW_HEALTH        names that report "starting" for 2 polls after a start
  #   UNHEALTHY          names that start but report "unhealthy"
  printf '%s\n' ${SLOW_HEALTH:-} | grep -v '^$' > "$SCEN/slow-health" || true
  printf '%s\n' ${UNHEALTHY:-} | grep -v '^$' > "$SCEN/unhealthy" || true
  # Optional scenario knobs, read from the caller's environment:
  #   STATS_ROWS         `docker stats` output (unset = stats fails, ps fallback)
  #   START_FAILS        how many `systemctl start docker.service` calls fail
  #   SYSTEMD_RESTARTS=1 a failed start comes up on its own (Restart=always)
  [ -n "${STATS_ROWS:-}" ] && printf '%s\n' "$STATS_ROWS" > "$SCEN/stats"
  echo "${START_FAILS:-0}" > "$SCEN/start-fails-docker"
  [ -n "${SYSTEMD_RESTARTS:-}" ] && : > "$SCEN/systemd-restarts"
  $RUN_AS rm -f "$SHED_LIST" "$FIRED"
  #   STALE_SHED_LIST    lines already in the shed-list when the shedder starts
  [ -n "${STALE_SHED_LIST:-}" ] && printf '%s\n' $STALE_SHED_LIST | $RUN_AS tee "$SHED_LIST" >/dev/null

  mk_stub() { # $1 = command name; body on stdin. Paths baked, not inherited:
              # the stubs must work regardless of how the shedder is invoked.
    { echo '#!/bin/sh'; echo "SCEN='$SCEN'"; echo "AWK_REAL='$AWK_REAL'"; cat; } > "$SCEN/bin/$1"
    chmod +x "$SCEN/bin/$1"
  }

  # The shedder reads PSI only through `awk ... /proc/pressure/<kind>`, so that
  # is the seam for feeding pressure. Every other awk call (the docker-stats
  # ordering in shed_non_tier1) is delegated to the real one — stubbing it
  # wholesale would silently change the code path under test.
  mk_stub awk <<'STUB'
case " $* " in
  *"/proc/pressure/memory"*)
    n=$(cat "$SCEN/psi-cursor")
    v=$(sed -n "${n}p" "$SCEN/psi-seq")
    # A "U" prefix means something outside the shedder (a ship, a human)
    # brought docker up long ago — so no start grace applies. "enter" is
    # removed, not set to 1µs: 1µs after boot is an age equal to the host's
    # uptime, and a GHA runner is often up <180s, so E's second episode sat in
    # GRACE, never shed, and failed CI (lint-pipeline 36704742910).
    case "$v" in U*) rm -f "$SCEN/docker-down" "$SCEN/enter"; v=${v#U} ;; esac
    if [ -z "$v" ]; then : > "$SCEN/psi-exhausted"; echo 0
    else echo $((n + 1)) > "$SCEN/psi-cursor"; echo "$v"; fi ;;
  *"/proc/pressure/"*) echo 0 ;;   # cpu/io are logged, never shed on
  *) exec "$AWK_REAL" "$@" ;;
esac
STUB

  # The shedder loops forever by design, so the scenario ends when the scripted
  # pressure runs out: SIGTERM the shell that called us. A wall-clock timeout
  # would make the assertions depend on how fast the box is.
  mk_stub sleep <<'STUB'
echo "sleep:$1" >> "$SCEN/timeline"
if [ -e "$SCEN/psi-exhausted" ]; then kill -TERM "$PPID" 2>/dev/null; fi
exit 0
STUB

  mk_stub docker <<'STUB'
echo "$*" >> "$SCEN/docker-calls"
cmd="$1"; shift
case "$cmd" in
  ps) cat "$SCEN/running" ;;
  # `docker stats` is timeout-guarded in shed_non_tier1 because it is unreliable
  # under thrash; by default fail it so the `docker ps` fallback is exercised.
  stats) [ -f "$SCEN/stats" ] || exit 1; cat "$SCEN/stats" ;;
  stop)
    # Snapshot the persisted list at the instant the shed happens — the shedder
    # deletes it on a successful un-shed, and it is the thing under test.
    cat /run/load-shedder.shed-list >> "$SCEN/shed-list-snapshot" 2>/dev/null || true
    for c in "$@"; do
      grep -vxF "$c" "$SCEN/running" > "$SCEN/running.tmp" || true
      mv "$SCEN/running.tmp" "$SCEN/running"
    done ;;
  start)
    for c in "$@"; do
      echo "$c" >> "$SCEN/starts"
      echo "start:$c" >> "$SCEN/timeline"
      grep -qxF "$c" "$SCEN/start-fails" 2>/dev/null && exit 1
      # What umami did on 2026-10-01 01:16: started while its depends_on
      # target was not up yet, failed its own DB check and exited.
      deps=$(grep "^$c|" "$SCEN/labels" | cut -d'|' -f4 | tr ',' '\n' | cut -d: -f1)
      proj=$(grep "^$c|" "$SCEN/labels" | cut -d'|' -f2)
      for d in $deps; do
        dc=$("$AWK_REAL" -F'|' -v p="$proj" -v s="$d" '$2 == p && $3 == s { print $1 }' "$SCEN/labels")
        if ! grep -qxF "$dc" "$SCEN/running" || [ -e "$SCEN/polls-$dc" ]; then
          echo "died:$c" >> "$SCEN/timeline"; continue 2
        fi
      done
      echo "$c" >> "$SCEN/running"
      grep -qxF "$c" "$SCEN/slow-health" && echo 2 > "$SCEN/polls-$c"
    done ;;
  inspect)
    [ "$1" = --format ] || exit 1
    fmt="$2"; shift 2
    rc=0
    for c in "$@"; do
      grep -qxF "$c" "$SCEN/exists" || { rc=1; continue; }
      case "$fmt" in
        *compose*)
          grep "^$c|" "$SCEN/labels" | sed 's|^|/|' | grep . || echo "/$c|||" ;;
        *State*)
          if ! grep -qxF "$c" "$SCEN/running"; then st=exited
          elif grep -qxF "$c" "$SCEN/unhealthy"; then st=unhealthy
          elif [ -e "$SCEN/polls-$c" ]; then
            n=$(($(cat "$SCEN/polls-$c") - 1)); st=starting
            if [ "$n" -le 0 ]; then rm -f "$SCEN/polls-$c"; else echo "$n" > "$SCEN/polls-$c"; fi
          elif grep -qxF "$c" "$SCEN/slow-health"; then st=healthy
          else st=running; fi
          echo "health:$c:$st" >> "$SCEN/timeline"
          echo "$st" ;;
      esac
    done
    exit $rc ;;
esac
exit 0
STUB

  # docker.service is up unless a full shed stopped it. "enter" is its
  # ActiveEnterTimestampMonotonic in usec — absent means "never", i.e. no grace.
  mk_stub systemctl <<'STUB'
echo "$*" >> "$SCEN/systemctl-calls"
now_us() { "$AWK_REAL" '{ printf "%d\n", $1 * 1000000 }' /proc/uptime; }
case "$1" in
  is-active)
    if [ -e "$SCEN/up-after-polls" ]; then
      n=$(($(cat "$SCEN/up-after-polls") - 1))
      if [ "$n" -le 0 ]; then rm -f "$SCEN/up-after-polls" "$SCEN/docker-down"; now_us > "$SCEN/enter"
      else echo "$n" > "$SCEN/up-after-polls"; fi
    fi
    [ -e "$SCEN/docker-down" ] && exit 3 ;;
  stop) [ "$2" = docker.service ] && : > "$SCEN/docker-down" ;;
  start)
    n=$(cat "$SCEN/start-fails-docker")
    if [ "$n" -gt 0 ]; then
      echo $((n - 1)) > "$SCEN/start-fails-docker"
      [ -e "$SCEN/systemd-restarts" ] && echo 2 > "$SCEN/up-after-polls"
      exit 1
    fi
    rm -f "$SCEN/docker-down"; now_us > "$SCEN/enter" ;;
  show) cat "$SCEN/enter" 2>/dev/null || echo 0 ;;
esac
exit 0
STUB

  mk_stub logger <<'STUB'
echo "$*" >> "$SCEN/log"
exit 0
STUB

  # Succeed so the shedder takes its normal notify path; the bodies are evidence.
  mk_stub curl <<'STUB'
echo "$*" >> "$SCEN/ntfy"
exit 0
STUB

  # 60s is a deadlock backstop, not the exit condition — the sleep stub is.
  # The group redirect silences the shell's own "Terminated" notice for the
  # SIGTERM we asked for; a stray "Terminated" in the middle of passing
  # assertions reads like a failure. A subshell would not work here: bash execs
  # it into timeout, leaving no shell inside to redirect.
  { timeout 60 $RUN_AS env PATH="$SCEN/bin:$PATH" sh "$SHEDDER" >/dev/null 2>&1 || true; } 2>/dev/null
}

log_has()  { grep -qF "$2" "$WORK/$1/log"; }
log_lacks() { ! log_has "$@"; }
log_count() { [ "$(grep -cF "$2" "$WORK/$1/log")" -eq "$3" ]; }
ntfy_has() { grep -qF "$2" "$WORK/$1/ntfy"; }
# Same multiset of names, order-independent.
same_set() { [ "$(sort "$1" | tr -d ' ')" = "$(printf '%s\n' $2 | sort | tr -d ' ')" ]; }
count_lines() { [ "$(wc -l < "$1")" -eq "$2" ]; }
count_calls() { [ "$(grep -c "^$3" "$WORK/$1/docker-calls")" -eq "$2" ]; }
# Pacing: the shedder must pause between each start, so no two start lines in
# the timeline are without a sleep between them, and the last start is followed
# by one. (Readiness polls may sit between a start and its pause.)
starts_are_paced() { awk '/^start:/ { if (open) bad = 1; open = 1 } /^sleep:/ { open = 0 } END { exit (bad || open) }' "$WORK/$1/timeline"; }
unshed_delay_used() { awk '/^start:/ { open = 1 } /^sleep:/ && open { sub(/^sleep:/, ""); print; open = 0 }' "$WORK/$1/timeline" | sort -u; }
# $2 occurs on a timeline line strictly before $3.
before() { awk -v a="$2" -v b="$3" '$0 == a && !sa { sa = NR } $0 == b && !sb { sb = NR } END { exit !(sa && sb && sa < sb) }' "$WORK/$1/timeline"; }
# Exact-token match, not grep -w: "-" is a word boundary, so -w would let a
# stopped ntfy-exporter satisfy an assertion about tier-1 ntfy.
never_touched() { ! tr ' ' '\n' < "$WORK/$1/docker-calls" | grep -qxF -e "$2"; }

# ── A: pressure clears, every shed container comes back ───────────────────
# Three crit ticks (>= crit, < page) reach NEED, then a clear tick fires the
# recovery edge; a trailing tick exhausts the sequence and ends the run.
echo "-- scenario A: crit shed -> pressure clears -> full un-shed"
run_scenario A "55 55 55 0 0" ""

assert "shed list persisted exactly the non-tier1 containers" \
  same_set "$WORK/A/shed-list-snapshot" "$SHEDDABLE"
assert "every name in the shed list got a docker start" \
  same_set "$WORK/A/starts" "$SHEDDABLE"
assert "no container was started twice" \
  count_lines "$WORK/A/starts" "$(printf '%s\n' $SHEDDABLE | wc -l)"
for t in $TIER1; do
  assert "tier-1 $t was never stopped or started" never_touched A "$t"
done
assert "starts are paced one-by-one (start always followed by a sleep)" starts_are_paced A
assert "umami-db was started before its dependent umami" before A "start:umami-db" "start:umami"
assert "no dependent died for want of its dependency" log_lacks A "UNSHED FAILED"
assert "un-shed reported success" log_has A "UNSHED: all shed containers restarted"
assert "recovery was notified loudly" ntfy_has A "RECOVERY — shed containers restarted"
assert "shed list cleared after a clean un-shed" test ! -e "$SHED_LIST"
assert "fired marker cleared after a clean un-shed" test ! -e "$FIRED"
echo "   unshed pause between starts (secs): $(unshed_delay_used A | tr '\n' ' ')"

# ── B: one container refuses to start — one shot PER EPISODE ──────────────
# Two full crit->clear cycles. The latch used to be per process lifetime, so
# the second episode refused to un-shed at all: git-proxy-api stayed down on
# oci-analytics after 2026-09-29 21:36 because an earlier episode had spent it.
# Each episode now gets exactly one attempt — every shed name started once per
# episode, never retried inside one.
echo "-- scenario B: a failed un-shed does not disarm the next episode"
run_scenario B "55 55 55 0 55 55 55 0 0" "agent-runner-1"

assert "the second crit cycle really did shed again" count_calls B 2 "stop "
assert "every shed name was started exactly once in EACH episode" \
  same_set "$WORK/B/starts" "$SHEDDABLE $SHEDDABLE"
assert "failure was reported, not swallowed" log_has B "UNSHED FAILED: still down: agent-runner-1"
assert "failure paged in both episodes" log_count B "UNSHED FAILED" 2
assert "the second episode was not refused by the first one's latch" \
  log_lacks B "already attempted and failed — not retrying"
assert "shed list kept for the human after a failed un-shed" $RUN_AS test -e "$SHED_LIST"

# ── C: `docker stats` under thrash names every container "--" ─────────────
# Measured on oci-analytics 2026-09-30 06:20: seven "--" rows were shed and
# persisted, and the un-shed then spent its shot on names that never existed.
echo "-- scenario C: '--' rows from docker stats are not container names"
STATS_ROWS="-- -- / --
-- -- / --
-- -- / --" run_scenario C "55 55 55 0 0" ""

assert "shed list holds the real non-tier1 containers, no '--'" \
  same_set "$WORK/C/shed-list-snapshot" "$SHEDDABLE"
assert "un-shed succeeded" log_has C "UNSHED: all shed containers restarted"

# The same "--" already sitting in /run from the pre-fix shedder (oci-analytics
# has 34 of them) must not fail every un-shed until the next reboot.
echo "-- scenario C2: a stale '--' left in the shed-list by the old shedder"
STALE_SHED_LIST="-- -- umami" run_scenario C2 "55 55 55 0 0" ""
assert "stale '--' did not fail the un-shed" log_has C2 "UNSHED: all shed containers restarted"
assert "'--' was never passed to docker start" never_touched C2 "--"

# ── D: the recovery the shedder starts must not be shed by its own spike ──
# Measured 2026-09-30 08:13: the single-shot start exited 1, systemd's
# Restart=always brought docker up 20s later, the shedder had already sampled
# once and latched RECOVERY FAILED — then dockerd's startup pushed memPSI to 89
# and a second SHED-PAGE stopped the daemon for good.
echo "-- scenario D: failed-then-restarted docker start, then startup pressure"
START_FAILS=1 SYSTEMD_RESTARTS=1 run_scenario D "70 70 70 0 90 90 90 90 0 0" ""

assert "recovery waited for systemd's retry instead of latching" \
  log_has D "RECOVERY: docker.service started"
assert "no false RECOVERY FAILED" log_lacks D "RECOVERY FAILED"
assert "startup pressure was held in grace" log_has D "GRACE:"
assert "exactly one full shed — the recovery was not shed again" log_count D "SHED-PAGE:" 1

# ── E: a spent recovery latch re-arms once docker is seen up again ─────────
# The first start fails for real (no systemd retry). Docker is then brought up
# from outside; the next full-shed episode must get its own recovery attempt.
echo "-- scenario E: recovery latch is per episode"
START_FAILS=1 run_scenario E "70 70 70 0 U0 70 70 70 0 0" ""

assert "first episode's failed start was reported" log_has E "RECOVERY FAILED"
assert "latch re-armed when docker came back" log_has E "RE-ARMED"
# Without these the recovery assertion is only as good as the fixture: a second
# episode that never shed has nothing to recover and fails for the wrong reason.
assert "second episode's pressure was counted, not graced" log_lacks E "GRACE:"
assert "second episode really did a full shed" log_count E "SHED-PAGE:" 2
assert "second episode's recovery restarted docker" log_count E "RECOVERY: docker.service started" 1
assert "second episode was not refused" log_lacks E "restart already attempted and failed"

# ── F: a dependency that takes its time to turn healthy ───────────────────
# Started first is not enough: umami's DB check runs seconds after its start,
# so umami-db has to be HEALTHY before umami is started, not merely started.
echo "-- scenario F: dependent waits for its dependency's healthcheck"
SLOW_HEALTH="umami-db" run_scenario F "55 55 55 0 0" ""

assert "umami-db's healthcheck was polled until healthy" before F "health:umami-db:starting" "health:umami-db:healthy"
assert "umami was started only after umami-db reported healthy" before F "health:umami-db:healthy" "start:umami"
assert "un-shed succeeded" log_has F "UNSHED: all shed containers restarted"

# ── G: started but unhealthy is a failure, not a success ──────────────────
# The verdict used to be "does docker ps list it right after its start" — a
# container that starts and then fails its healthcheck read as restored.
echo "-- scenario G: a container that comes up unhealthy is reported FAILED"
UNHEALTHY="agent-runner-2" run_scenario G "55 55 55 0 0" ""

assert "unhealthy container reported as still down" log_has G "UNSHED FAILED: still down: agent-runner-2"
assert "its healthy peers were still all started" same_set "$WORK/G/starts" "$SHEDDABLE"

$RUN_AS rm -f "$SHED_LIST" "$FIRED"

if [ "$FAILED" -ne 0 ]; then
  # The shedder's own log is the only thing that says WHY; without it the
  # previous failure needed a local re-render to diagnose.
  for l in "$WORK"/*/log; do sed "s|^|   ${l%/log}: |; s|$WORK/||" "$l"; done | grep -v 'breach' || true
  echo "FAIL: $FAILED runtime assertion(s) failed — the shed has no working inverse"
  exit 1
fi
echo "PASS: shed is reversible, paced, dependency-ordered, one shot per episode, and does not shed its own recovery"
